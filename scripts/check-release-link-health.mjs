import { readFile } from 'node:fs/promises';
import { reviewedCorrections, reviewedLocationLinks } from './lib/reviewed-corrections.mjs';
import { policyPath } from './lib/link-access-policy.mjs';
import { validateLinkHealth } from './lib/validate-link-health.mjs';
const read = async path => JSON.parse(await readFile(new URL('../'+path, import.meta.url),'utf8'));
const report = await read('data/build/source-link-health-report.json');
const policy = await read(policyPath);
const inputs = {};
for (const [key,name] of [['catalog','catalog'],['firstParty','first-party-sources'],['facts','structured-place-facts'],['city','city-events']]) inputs[key] = await read('data/build/'+name+'.json');
const expected = process.env.SOURCE_COMMIT_SHA || process.env.GITHUB_SHA;
if (process.env.GITHUB_RUN_ID && report.sourceWorkflowRunId !== process.env.GITHUB_RUN_ID) throw Error('Link audit workflow run mismatch');
validateLinkHealth(report,inputs,policy,expected);
const corrected = new Set(reviewedCorrections.records.filter(item => item.fields.website).map(item => item.fields.website));
for (const item of reviewedCorrections.additions) if (item.website) corrected.add(item.website);
for (const item of reviewedLocationLinks(inputs.catalog.restaurants)) corrected.add(item.url);
const failures = report.broken.filter(item => corrected.has(item.url));
if (failures.length) throw Error('Reviewed current official URL failed repeated 404/410: ' + failures.map(item => item.url).join(', '));
console.log(JSON.stringify({sourceCommitSha:expected, ...report.counts, policy:'Require complete same-head assessment and genuine response receipts; policy-held destinations remain explicit, unattempted and inconclusive. New restrictions require reviewed durable policy updates. Confirmed broken reviewed links block release; held/restricted/timeout rows never prove closure.'},null,2));
