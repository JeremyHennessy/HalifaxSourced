import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
const source = await readFile(new URL('../app-detail.js', import.meta.url), 'utf8');
let headerBottom = 84, tabHeight = 48, stickyTop = 84, reducedMotion = false;
const scrollCalls = [], focuses = [], attributes = [], resizeListeners = [];
const window = { scrollY: 300, getComputedStyle: () => ({ top: tabs.style.top || `${stickyTop}px` }), addEventListener: (type, handler) => { assert.equal(type, 'resize'); resizeListeners.push(handler); }, matchMedia: () => ({ matches: reducedMotion }), scrollTo: options => { scrollCalls.push(options); window.scrollY = options.top; } };
const section = { style: {}, scrollIntoView: function(options) { scrollCalls.push(options); window.scrollY = Math.max(0, window.scrollY + this.getBoundingClientRect().top - parseFloat(this.style.scrollMarginTop)); }, getClientRects: () => [{}], getBoundingClientRect: () => ({ top: 1000 - window.scrollY }), setAttribute: (...args) => attributes.push(args), focus: options => focuses.push(options) };
const hidden = { ...section, getClientRects: () => [] };
const header = { getBoundingClientRect: () => ({ bottom: headerBottom }) };
const tabs = { style: {}, getBoundingClientRect: () => ({ height: tabHeight }) };
const targets = { siteHeader: header, detailMenu: section, detailSources: section, detailOverview: hidden, detailInfo: section };
let listener, tabsVisible = true;
const link = { getAttribute: () => '#detailMenu', addEventListener: (name, handler) => { assert.equal(name, 'click'); listener = handler; } };
const location = { hash: '#restaurant/fixture' };
const context = vm.createContext({ window, document: { getElementById: id => targets[id], querySelector: () => tabsVisible ? tabs : null, querySelectorAll: () => [link] }, location, history: { pushState: () => { throw Error('Anchor changed history'); }, replaceState: () => { throw Error('Anchor changed history'); } } });
vm.runInContext(source.slice(0, source.indexOf('function renderRestaurantDetail')), context);
context.bindRestaurantDetailTabs();
context.bindRestaurantDetailTabs();
assert.equal(resizeListeners.length, 1, 'Repeated detail renders must not accumulate resize listeners');
assert.equal(tabs.style.top, '84px');
tabsVisible = false; headerBottom = 131; resizeListeners[0]();
assert.equal(tabs.style.top, '84px', 'Resize on another route cannot mutate a detached detail bar');
tabsVisible = true; resizeListeners[0]();
assert.equal(tabs.style.top, '131px', 'Resize updates the current detail bar before the next real click');
let prevented = 0;
const click = () => listener({ preventDefault: () => prevented++ });
for (const dimensions of [[84,48,84],[131,48,124],[131,48,72],[112,44,112],[80,48,100]]) {
  [headerBottom, tabHeight, stickyTop] = dimensions;
  click();
  assert.equal(window.scrollY, 1000 - headerBottom - tabHeight - 8);
  assert.equal(tabs.style.top, `${headerBottom}px`, 'Wrapped headers must not obscure the clickable tabs');
  const previous = window.scrollY;
  click();
  assert.equal(window.scrollY, previous, 'Repeated clicks must not accumulate offsets');
  assert.equal(scrollCalls.at(-1).behavior, 'smooth');
  assert.equal(location.hash, '#restaurant/fixture', 'Keep the restaurant hash untouched');
}
reducedMotion = true; click(); assert.equal(scrollCalls.at(-1).behavior, 'instant');
assert(focuses.every(options => options.preventScroll === true));
assert(attributes.every(([name,value]) => name === 'tabindex' && value === '-1'));
link.getAttribute = () => '#detailOverview'; click();
assert.equal(focuses.length, scrollCalls.length, 'Hidden mobile overview falls back to visible Info');
link.getAttribute = () => '#missing'; const count = scrollCalls.length; click();
assert.equal(scrollCalls.length,count,'Missing targets must not schedule scroll work');
assert.equal(prevented,count+1,'Every local anchor prevents browser hash navigation');
window.scrollY = 0; targets.detailMenu = { ...section, getBoundingClientRect: () => ({ top: 20 }) };
link.getAttribute = () => '#detailMenu'; click(); assert.equal(window.scrollY,0,'Do not request negative scroll positions');
console.log('Detail anchor offsets passed: live header/tab measurements, responsive changes, singleton resize lifecycle, repeats, focus, reduced motion, missing/hidden targets and route isolation.');
